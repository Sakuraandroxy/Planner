"""Actual dependencies of the HTTP lifecycle manager."""
from typing import Protocol

from planner.domain.server import TaskSubmission, WorkerEvent
from planner.domain.server import WorkerMode
from planner.domain.result import MissionResult


class BackendWorker(Protocol):
    def submit(self, task: TaskSubmission) -> None: ...
    def poll(self) -> WorkerEvent | None: ...
    def terminate(self) -> None:
        """Return only after this worker cannot send further flight commands."""
        ...
    def shutdown(self) -> None: ...


class ConnectionMonitor(Protocol):
    def check(self) -> bool: ...
    def close(self) -> None: ...


class BackendSession(Protocol):
    @property
    def connection_lost(self) -> bool: ...
    def prepare(self, mode: WorkerMode) -> None: ...
    def execute(self, instruction: str) -> MissionResult: ...
    def hold(self) -> None: ...
    def idle_tick(self) -> None: ...
    def close(self) -> None: ...

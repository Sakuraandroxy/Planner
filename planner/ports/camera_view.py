"""One task-owned, temporary adjustment of a single attached camera."""
from typing import Protocol
from planner.domain.visual_goal_above import CameraMountPose, Point3


class CameraView(Protocol):
    def read_mount(self) -> CameraMountPose: ...
    def point(self, pitch_deg: float, yaw_deg: float = 0.0) -> None: ...
    def point_at_world(self, point: Point3) -> None: ...
    def point_direction_world(self, direction: Point3) -> None:
        """Aim along a nonzero world-NED direction; do not move the camera origin."""
        ...
    def point_down(self) -> None: ...
    def restore(self, mount: CameraMountPose) -> None: ...
